const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'pinned-user.js'), 'utf8');
const version = source.match(/const SCRIPT_VERSION = '(\d+\.\d+\.\d+)';/)?.[1];
if (!version) throw new Error('Missing SCRIPT_VERSION');
new (require('node:vm').Script)(source);
const file = path.join(root, 'pinned-user.json');
const pkg = JSON.parse(fs.readFileSync(file, 'utf8'));
const loaderFile = path.join(root, 'loader.js');
const loader = fs.readFileSync(loaderFile, 'utf8').replace(/const VERSION = '\d+\.\d+\.\d+';/, `const VERSION = '${version}';`);
fs.writeFileSync(loaderFile, loader);
pkg.content = loader;
pkg.version = version;
pkg.info = `版本：${version}\n指定版本加载版。通过「📌 常用 User」管理置顶。\n更新时只修改脚本入口的 VERSION，保存并重新启用；版本必须已经发布。\n启动时从 jsDelivr 加载对应版本，置顶记录沿用旧版；不再提供检查更新按钮。`;
pkg.button.buttons = pkg.button.buttons.filter(button => button.name !== '🔄 检查更新');
fs.writeFileSync(file, JSON.stringify(pkg, null, 2) + '\n');
fs.writeFileSync(path.join(root, 'pinned-user.module.js'), `// Generated by scripts/build.cjs; do not edit.\nexport const version = '${version}';\nexport default function startPinnedUser() {\n${source}\n}\n`);
const manifestFile = path.join(root, 'package.json');
const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
manifest.version = version;
fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 2) + '\n');
console.log(`Built v${version}`);
